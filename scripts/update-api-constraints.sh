#!/usr/bin/env bash
# Re-pin the exact Python package versions the `api` image installs.
#
#   scripts/update-api-constraints.sh
#
# Resolves api/requirements.txt and common/ from scratch in the same base image
# as api/Dockerfile, then writes every installed version to api/constraints.txt.
# Run it when you change a range in api/requirements.txt or common/pyproject.toml,
# or to take newer versions on purpose. Then regenerate the web types
# (scripts/gen-api-types.sh) and commit all of it together.
#
# Needs only Docker. Works from Git Bash on Windows too.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

# Git Bash: keep MSYS from rewriting /paths in docker arguments, and hand
# docker a Windows path for the mount.
export MSYS_NO_PATHCONV=1
mount_root="$root"
if pwd -W >/dev/null 2>&1; then mount_root="$(pwd -W)"; fi

base_image="$(sed -n 's/^FROM \([^ ]*\).*/\1/p' api/Dockerfile | head -n 1)"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

docker run --rm --platform linux/amd64 -v "$mount_root:/repo:ro" "$base_image" sh -euc '
  cp -r /repo/common /tmp/common
  pip install --quiet --no-cache-dir --root-user-action=ignore --disable-pip-version-check --default-timeout=60 /tmp/common -r /repo/api/requirements.txt
  pip freeze --exclude reach-loop-common
' > "$tmp"

{
  echo "# Exact versions for the api image and api dev installs (pip -c)."
  echo "# Generated by scripts/update-api-constraints.sh from $base_image; do not edit by hand."
  cat "$tmp"
} > api/constraints.txt

echo "Wrote api/constraints.txt ($(grep -vc '^#' api/constraints.txt) packages)"
