#!/usr/bin/env bash
# Re-pin the exact Python package versions the api image installs.
#
#   scripts/update-api-constraints.sh
#
# Resolves api/requirements.txt and common/ from scratch in the api image's base
# image (python:3.12-slim, linux/amd64) and rewrites api/constraints.txt with
# every installed version. Run it after changing a range in api/requirements.txt
# or common/pyproject.toml, or to take newer versions on purpose. Then reinstall
# the dev env, run scripts/gen-api-types.sh and the api tests, and commit it all
# together (see docs/local-development.md, "Bump the pinned versions").
#
# Needs only Docker. The repo is mounted read-only, so nothing is written into
# it except api/constraints.txt. Works from Git Bash on Windows too.
#
# Ported from PR #32 by @balintpragai.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

host_root="$root"
case "$(uname -s)" in
  MINGW* | MSYS* | CYGWIN*)
    export MSYS_NO_PATHCONV=1  # stop Git Bash rewriting /repo into a Windows path
    host_root="$(pwd -W)"      # C:/Users/... instead of /c/Users/...
    ;;
esac

base_image="$(sed -n 's/^FROM \([^ ]*\).*/\1/p' api/Dockerfile | head -n 1)"

echo "==> Resolving api/requirements.txt and common/ in $base_image (linux/amd64)"
pins="$(docker run --rm --platform linux/amd64 -v "$host_root:/repo:ro" "$base_image" sh -euc '
  cp -r /repo/common /tmp/common
  pip install --quiet --no-cache-dir --root-user-action=ignore --disable-pip-version-check \
    /tmp/common -r /repo/api/requirements.txt
  pip freeze --exclude reach-loop-common
')"

# Only replace the file once resolving has succeeded.
{
  echo "# Exact versions for the api image ($base_image, linux/amd64) and the api dev env."
  echo "# The OpenAPI spec in web/openapi.json depends on fastapi, starlette and pydantic,"
  echo "# so the same commit must always install the same versions."
  echo "#"
  echo "# Generated by scripts/update-api-constraints.sh. To bump everything, re-run it;"
  echo "# see docs/local-development.md (\"Bump the pinned versions\")."
  printf '%s\n' "$pins"
} > api/constraints.txt

echo "==> Wrote api/constraints.txt ($(grep -vc '^#' api/constraints.txt) packages)"
git --no-pager diff --stat -- api/constraints.txt
